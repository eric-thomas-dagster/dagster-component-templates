class TavilyIngestionComponent(Component, Model, Resolvable):
    """Run search queries against Tavily (https://tavily.com), an AI-native search API
    purpose-built for RAG/agent pipelines (as opposed to a general web index like Google),
    and land the results as flat rows: one row per (query, result).

    Queries come from `queries` (a static comma-separated list), from an upstream asset's
    DataFrame column (`upstream_asset_key` + `query_column`), or both -- when both are set,
    the static queries and the per-row upstream queries are all run (deduplicated).

    Output rows are shaped to feed `document_chunker` -> `vector_store_writer` directly:
    `content` holds the result's text snippet (point document_chunker's `source_column` at
    it) and `query`/`title`/`url`/`result_id` are good `metadata_columns` to preserve through
    chunking.

    Tavily also has a separate `/extract` endpoint (URL -> content, similar to
    firecrawl_ingestion/jina_reader_ingestion) -- this component is search-only and does not
    cover it.

    Example:

        ```yaml
        type: dagster_community_components.TavilyIngestionComponent
        attributes:
          asset_name: tavily_search_results
          api_key_env_var: TAVILY_API_KEY
          queries: "dagster asset checks, snowflake dynamic tables"
          search_depth: advanced
          max_results: 10
        ```
    """

